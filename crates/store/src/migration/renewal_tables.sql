-- The two axes and the place (docs/agents.md, 「Two axes」): the supervisors, the roles and the repositories,
-- each a table of its own, the sessions roles keep, and the role slots. What the rows of the retired tables
-- become is carried by the migration's own code between this file and the one that drops them.

-- A supervisor's whole declaration and what its one resident program stands on now (docs/supervisors.md,
-- 「What a supervisor row holds」). Its provider order is a JSON list of entries, its warming a JSON object
-- from a provider to whether its prefix is kept warm there.
CREATE TABLE "supervisors" (
  "name" text,
  "label" text,
  "owner_account" bigint,
  "aliases" text,
  "wake_words" text,
  "icon" text,
  "prompts" text,
  "brain_folder" text,
  "voice" text,
  "window_seconds" bigint,
  "session_scope" text NOT NULL,
  "turn_shape" text NOT NULL,
  "default_answerer" bigint NOT NULL DEFAULT 0,
  "repository" text,
  "provider_order" text NOT NULL DEFAULT '[]',
  "quota_share" double precision NOT NULL DEFAULT 0.01,
  "warming" text NOT NULL DEFAULT '{}',
  "fold_ratio" double precision NOT NULL DEFAULT 0.85,
  "builtin" bigint NOT NULL DEFAULT 0,
  "chat_id" bigint,
  "session_id" text,
  "last_mode" text,
  "last_model" text,
  "last_effort" text,
  "last_run_at" bigint,
  "last_keepalive_at" bigint,
  "runs" bigint NOT NULL DEFAULT 0,
  "context_tokens" bigint,
  "prompt_changed_at" bigint,
  "herdr_label" text,
  "created_at" bigint NOT NULL,
  "updated_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("name")
);

-- A repository: a place runs work in, never an agent (docs/repositories.md, 「What a repository row holds」).
CREATE TABLE "repositories" (
  "name" text,
  "label" text,
  "owner_account" bigint,
  "path" text NOT NULL,
  "node" text,
  "support_count" bigint NOT NULL DEFAULT 0,
  "prefix_documents" text,
  "preamble" text,
  "prompts" text,
  "dev_command" text,
  "pinned_provider" text,
  "pinned_model" text,
  "downgrade_heal" bigint NOT NULL DEFAULT 1,
  "created_at" bigint NOT NULL,
  "updated_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("name")
);

-- A repository's checkouts kept on the work nodes, each a support worktree of it standing on one node
-- (docs/worker-slots.md).
CREATE TABLE "repository_node_checkouts" (
  "repository" text NOT NULL,
  "node" text NOT NULL,
  "path" text NOT NULL,
  "created_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("repository", "node")
);

-- The roles: the executing axis (docs/agent-roles.md, 「What a role row holds」).
ALTER TABLE "agent_roles" RENAME TO "roles";
ALTER TABLE "agent_role_seeded" RENAME TO "role_seeded";
ALTER TABLE "roles" ADD COLUMN "description" text;
ALTER TABLE "roles" ADD COLUMN "line" text NOT NULL DEFAULT 'worker';
ALTER TABLE "roles" ADD COLUMN "provider_order" text NOT NULL DEFAULT '[]';
ALTER TABLE "roles" ADD COLUMN "quota_share" double precision NOT NULL DEFAULT 0.01;
ALTER TABLE "roles" ADD COLUMN "fold_ratio" double precision NOT NULL DEFAULT 0.85;
ALTER TABLE "roles" ADD COLUMN "callable" bigint NOT NULL DEFAULT 0;

-- The sessions roles keep, one row a session a role's run opened (docs/sessions.md, 「A role's session」).
CREATE TABLE "role_sessions" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY,
  "role" text NOT NULL,
  "path" text NOT NULL,
  "provider" text NOT NULL,
  "model" text NOT NULL,
  "effort" text NOT NULL DEFAULT '',
  "account" text,
  "command_key" text NOT NULL,
  "session" text NOT NULL,
  "opened_at" bigint NOT NULL,
  "answered_at" bigint,
  "runs" bigint NOT NULL DEFAULT 0,
  "context_tokens" bigint,
  "context_share" double precision,
  "held" bigint NOT NULL DEFAULT 0,
  "dropped" bigint NOT NULL DEFAULT 0,
  PRIMARY KEY ("id")
);

CREATE INDEX "role_sessions_key" ON "role_sessions" ("role", "path", "provider", "model", "command_key", "id");
CREATE INDEX "role_sessions_history" ON "role_sessions" ("role", "id");

