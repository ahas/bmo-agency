-- The support checkouts a repository set to `auto` has made, each by its slot, from when it was recorded.
CREATE TABLE "support_checkouts" (
  "repository" text NOT NULL REFERENCES "repositories" ("name") ON DELETE CASCADE ON UPDATE CASCADE,
  "slot" bigint NOT NULL,
  "made_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("repository", "slot")
);

-- Every support checkout a repository's count stood for is recorded, so it keeps them as it goes `auto`.
INSERT INTO "support_checkouts" ("repository", "slot", "made_at")
  SELECT r."name", s."slot", (extract(epoch FROM now()) * 1000)::bigint
  FROM "repositories" r, generate_series(2, 1 + r."support_count") AS s ("slot")
  WHERE r."support_count" > 0;

-- A repository's support count: null is `auto`, every repository's default and every repository's now.
ALTER TABLE "repositories" ALTER COLUMN "support_count" DROP NOT NULL;
ALTER TABLE "repositories" ALTER COLUMN "support_count" SET DEFAULT NULL;
UPDATE "repositories" SET "support_count" = NULL;
