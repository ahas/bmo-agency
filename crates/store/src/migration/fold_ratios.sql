-- The fold ratio of each provider at each tier (docs/sessions.md, 「Session compaction」): the share of a
-- model's window a session may fill before it is folded once the turn that crossed it is over. A
-- provider is recorded as given once its ratios were seeded, so a ratio the owner set is never seeded
-- over.
CREATE TABLE "fold_ratios" (
  "provider" text NOT NULL,
  "tier" text NOT NULL,
  "ratio" double precision NOT NULL,
  "set_at" bigint NOT NULL,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("provider", "tier")
);

CREATE TABLE "fold_ratio_seeded" (
  "provider" text,
  rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  PRIMARY KEY ("provider")
);
